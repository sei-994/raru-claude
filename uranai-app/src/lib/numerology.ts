const masterNumbers = [11, 22, 33];

export function calculateLifePathNumber(year: number, month: number, day: number): number {
  const reduceToSingle = (n: number): number => {
    while (n > 9 && !masterNumbers.includes(n)) {
      n = String(n).split("").reduce((sum, d) => sum + Number(d), 0);
    }
    return n;
  };

  const yearReduced = reduceToSingle(year);
  const monthReduced = reduceToSingle(month);
  const dayReduced = reduceToSingle(day);
  const total = yearReduced + monthReduced + dayReduced;

  return reduceToSingle(total);
}

